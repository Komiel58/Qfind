let searchInput, searchButton, clearButton, resultsContainer;

// 検索実行関数
function performSearch() {
    const query = searchInput.value.trim().toLowerCase();
    
    // 検索フィルタリング
    let filteredResults = database.filter(item => {
        if (!query) return true; // キーワードがない場合はすべて表示
        const matchesQuestion = item.question.toLowerCase().includes(query);
        const matchesAnswer = item.answer.toLowerCase().includes(query);
        return matchesQuestion || matchesAnswer;
    });
    
    // 結果の表示
    displayResults(filteredResults);
}

// 結果表示関数
function displayResults(results) {
    if (results.length === 0) {
        resultsContainer.innerHTML = '<p class="no-results">検索結果が見つかりませんでした</p>';
        return;
    }
    
    const html = results.map(item => `
        <div class="result-item">
            <div class="question-section">
                <span class="result-type question">問題</span>
                <p class="result-content">${escapeHtml(item.question)}</p>
            </div>
            <div class="answer-section">
                <span class="result-type answer">回答</span>
                <p class="result-content">${escapeHtml(item.answer)}</p>
            </div>
            <p class="result-meta">投稿日時: ${item.timestamp}</p>
        </div>
    `).join('');
    
    resultsContainer.innerHTML = html;
}

// HTMLエスケープ関数
function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}

